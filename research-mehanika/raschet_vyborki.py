# -*- coding: utf-8 -*-
"""
Расчёт размера выборки для аудита видимости бренда в ответах генеративных систем
(Алиса / GigaChat / ChatGPT и т.п.). Раздел 5 «Метрики».

Только стандартная библиотека Python (statistics.NormalDist), без scipy.
Запуск:  python3 raschet_vyborki.py
Проверено 2026-09-25 на Python 3 в песочнице.

Что считается:
 1) 95% доверительный интервал Уилсона для доли (ширина при n = 30..400, p = 0.1/0.3/0.5);
 2) n на группу для сравнения двух независимых долей (alpha=0.05 двусторонний, мощность 0.8);
 3) эффект дизайна для коррелированных повторов одного промпта: DEFF = 1 + (m-1)*ICC;
 4) минимально обнаружимая разница (MDE) для реалистичных бюджетов аудита.
"""
from math import sqrt, ceil
from statistics import NormalDist

Z = NormalDist()
ALPHA = 0.05
POWER = 0.80
Z_A = Z.inv_cdf(1 - ALPHA / 2)   # 1.95996
Z_B = Z.inv_cdf(POWER)           # 0.84162


def wilson(x, n, z=Z_A):
    """95% интервал Уилсона для доли x/n. Возвращает (нижняя, верхняя)."""
    if n == 0:
        return (0.0, 1.0)
    p = x / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (max(0.0, centre - half), min(1.0, centre + half))


def n_two_props(p1, p2, alpha=ALPHA, power=POWER):
    """n на КАЖДУЮ группу, двусторонний тест разности двух независимых долей
    (нормальное приближение, формула Флейсса без поправки на непрерывность):
    n = [z_{a/2}*sqrt(2*pb*(1-pb)) + z_b*sqrt(p1(1-p1)+p2(1-p2))]^2 / (p1-p2)^2
    """
    za = Z.inv_cdf(1 - alpha / 2)
    zb = Z.inv_cdf(power)
    pb = (p1 + p2) / 2
    num = (za * sqrt(2 * pb * (1 - pb)) + zb * sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2
    return num / (p1 - p2) ** 2


def n_two_props_cc(p1, p2, alpha=ALPHA, power=POWER):
    """То же с поправкой Флейсса на непрерывность (консервативнее)."""
    n = n_two_props(p1, p2, alpha, power)
    d = abs(p1 - p2)
    return n / 4 * (1 + sqrt(1 + 4 / (n * d))) ** 2


def deff(m, icc):
    """Эффект дизайна: m повторов одного промпта, ICC — внутрикластерная корреляция."""
    return 1 + (m - 1) * icc


def mde(p1, n_eff, alpha=ALPHA, power=POWER):
    """Минимальный рост доли от p1, который обнаружим при n_eff на группу (поиск перебором)."""
    p2 = p1
    while p2 < 0.999:
        p2 += 0.001
        if n_two_props(p1, p2, alpha, power) <= n_eff:
            return p2 - p1
    return float("nan")


def main():
    print(f"z_(alpha/2) = {Z_A:.5f}; z_(beta) = {Z_B:.5f}\n")

    # 1. Ширина интервала Уилсона
    print("Таблица 1. 95% интервал Уилсона: границы и полная ширина (п.п.)")
    print("| n | p=0,1 | p=0,3 | p=0,5 |")
    print("|---|---|---|---|")
    for n in (30, 50, 100, 200, 400):
        cells = []
        for p in (0.1, 0.3, 0.5):
            x = p * n  # доля может давать дробный x — для иллюстрации допустимо
            lo, hi = wilson(x, n)
            cells.append(f"{lo*100:.1f}–{hi*100:.1f}% (ширина {(hi-lo)*100:.1f})")
        print(f"| {n} | " + " | ".join(cells) + " |")
    print()

    # 2. n для сравнения двух долей
    print("Таблица 2. n на группу: alpha=0,05 (двусторонний), мощность 0,8")
    print("| сценарий | n без поправки | n с поправкой на непрерывность | всего ответов (2 группы, с поправкой) |")
    print("|---|---|---|---|")
    for p1, p2 in ((0.10, 0.20), (0.20, 0.30), (0.30, 0.45), (0.05, 0.15), (0.50, 0.60)):
        n0 = ceil(n_two_props(p1, p2))
        n1 = ceil(n_two_props_cc(p1, p2))
        print(f"| {int(p1*100)}% → {int(p2*100)}% | {n0} | {n1} | {2*n1} |")
    print()

    # 3. Эффект дизайна
    print("Таблица 3. Эффект дизайна DEFF = 1+(m-1)*ICC и эффективный n при 360 ответах")
    print("| повторов на промпт m | промптов при 360 ответах | ICC=0,3 | ICC=0,5 | ICC=0,7 |")
    print("|---|---|---|---|---|")
    total = 360
    for m in (1, 2, 3, 5, 10):
        k = total // m
        cells = [f"DEFF {deff(m, r):.1f} → n_eff {total/deff(m, r):.0f}" for r in (0.3, 0.5, 0.7)]
        print(f"| {m} | {k} | " + " | ".join(cells) + " |")
    print()

    # 4. Сценарии аудита
    print("Таблица 4. Реалистичные планы аудита (на ОДНУ систему), ICC=0,5")
    print("| план | ответов на систему | n_eff | ±полуширина ДИ при p=0,3 (п.п.) | MDE от 10% | MDE от 30% |")
    print("|---|---|---|---|---|---|")
    for k, m in ((20, 3), (30, 3), (40, 3), (50, 2), (60, 2), (100, 1)):
        n = k * m
        ne = n / deff(m, 0.5)
        lo, hi = wilson(0.3 * ne, ne)
        print(f"| {k} промптов × {m} повтора | {n} | {ne:.0f} | ±{(hi-lo)/2*100:.1f} | +{mde(0.10, ne)*100:.0f} п.п. | +{mde(0.30, ne)*100:.0f} п.п. |")
    print()
    print("Замечание: MDE — для сравнения двух НЕЗАВИСИМЫХ замеров (например, «до» и «после»")
    print("на новых прогонах тех же промптов, или две системы). Для сравнения бренда с конкурентом")
    print("в ОДНИХ И ТЕХ ЖЕ ответах корректнее парный тест (Макнемара) — он обычно мощнее.")


def fisher_two_sided(a, n1, b, n2):
    """Точный тест Фишера (двусторонний) для a/n1 против b/n2, через гипергеометрию."""
    from math import comb
    k = a + b
    N = n1 + n2
    def pr(x):
        return comb(n1, x) * comb(n2, k - x) / comb(N, k)
    p_obs = pr(a)
    lo, hi = max(0, k - n2), min(k, n1)
    return sum(pr(x) for x in range(lo, hi + 1) if pr(x) <= p_obs * (1 + 1e-9))


def audit_plans():
    print("Таблица 5. Аудит за 19 900 руб.: три плана по ~270 ответов (3 системы), ICC=0,5")
    print("| план | ответов всего | на систему | n_eff на систему | ±ДИ при p=0,3 | верхняя граница при 0 упоминаний | MDE от 10% | MDE от 30% |")
    print("|---|---|---|---|---|---|---|---|")
    for k, m in ((30, 3), (45, 2), (90, 1)):
        n = k * m
        ne = n / deff(m, 0.5)
        lo, hi = wilson(0.3 * ne, ne)
        _, up0 = wilson(0, ne)
        print(f"| {k} промптов × {m} повт. × 3 системы | {n*3} | {n} | {ne:.0f} | ±{(hi-lo)/2*100:.1f} п.п. | {up0*100:.1f}% | +{mde(0.10, ne)*100:.0f} п.п. | +{mde(0.30, ne)*100:.0f} п.п. |")
    print()
    print("Пример из раздела 4: ошибки 6/30 до и 2/30 после исправления")
    print(f"  точный тест Фишера, p = {fisher_two_sided(6, 30, 2, 30):.3f}")
    lo1, hi1 = wilson(6, 30); lo2, hi2 = wilson(2, 30)
    print(f"  ДИ Уилсона: 6/30 = {lo1*100:.1f}–{hi1*100:.1f}%, 2/30 = {lo2*100:.1f}–{hi2*100:.1f}%")
    print(f"  тот же эффект на 200 ответах: 40/200 против 13/200, p = {fisher_two_sided(40, 200, 13, 200):.5f}")


if __name__ == "__main__":
    main()
    print()
    audit_plans()
